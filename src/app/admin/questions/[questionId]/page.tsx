import Link from "next/link";
import { notFound } from "next/navigation";
import { Trash2 } from "lucide-react";
import { PageHeader, Panel } from "@/components/admin/PageHeader";
import { QuestionForm, type LessonOption } from "@/components/admin/QuestionForm";
import { StatusBadge } from "@/components/admin/StatusBadge";
import { ActionButton } from "@/components/admin/ActionButton";
import { deleteQuestion, reviewQuestion } from "@/app/admin/actions/quizzes";
import { getAdminContext } from "@/lib/admin/guard";
import { isUuid } from "@/lib/admin/validation";
import type { OptionRow, QuestionRow } from "@/lib/admin/types";

export const metadata = { title: "Edit question" };

export default async function QuestionPage({ params }: { params: Promise<{ questionId: string }> }) {
  const { questionId } = await params;
  if (!isUuid(questionId)) notFound();
  const { supabase } = (await getAdminContext())!;
  const [{ data: qRaw }, { data: opts }, { data: links }, { data: courses }, { data: lessons }] = await Promise.all([
    supabase.from("questions").select("*").eq("id", questionId).maybeSingle(),
    supabase.from("question_options").select("*").eq("question_id", questionId).order("position"),
    supabase.from("quiz_questions").select("quizzes(id, title, status)").eq("question_id", questionId),
    supabase.from("courses").select("id, title").order("title"),
    supabase.from("lessons").select("id, title, course_id").order("position").limit(1000),
  ]);
  if (!qRaw) notFound();
  const q = qRaw as unknown as QuestionRow;
  const usedIn = ((links ?? []) as unknown as { quizzes: { id: string; title: string; status: string } | null }[]).map((l) => l.quizzes).filter(Boolean) as { id: string; title: string; status: string }[];

  return (
    <>
      <PageHeader eyebrow={q.source === "ai" ? "AI-generated question" : "Question"} title="Edit question" subtitle={<Link href="/admin/questions" className="underline underline-offset-4">Question bank</Link>}
        actions={<><StatusBadge status={q.review_status} />{q.published && <StatusBadge status="published" />}{q.archived && <StatusBadge status="archived" />}</>} />
      <div className="grid gap-8 xl:grid-cols-[1fr_20rem]">
        <QuestionForm question={q} options={(opts ?? []) as unknown as OptionRow[]} courses={(courses ?? []) as { id: string; title: string }[]} lessons={(lessons ?? []) as LessonOption[]} />
        <div className="space-y-6">
          <Panel title="Review" description={q.source === "ai" ? "Generated by AI. Check it against the lesson before approving." : "Only approved, published questions are shown to students."}>
            <div className="flex flex-wrap gap-2">
              {q.review_status !== "approved" && <ActionButton action={reviewQuestion} fields={{ questionId: q.id, op: "approve" }} variant="primary" className="h-9 px-3">Approve</ActionButton>}
              {q.review_status !== "rejected" && <ActionButton action={reviewQuestion} fields={{ questionId: q.id, op: "reject" }} variant="outline" className="h-9 px-3">Reject</ActionButton>}
              {q.review_status === "approved" && !q.archived && (q.published ? <ActionButton action={reviewQuestion} fields={{ questionId: q.id, op: "unpublish" }} variant="outline" className="h-9 px-3">Unpublish</ActionButton> : <ActionButton action={reviewQuestion} fields={{ questionId: q.id, op: "publish" }} variant="primary" className="h-9 px-3">Publish</ActionButton>)}
              {q.archived ? <ActionButton action={reviewQuestion} fields={{ questionId: q.id, op: "restore" }} variant="outline" className="h-9 px-3">Restore</ActionButton> : <ActionButton action={reviewQuestion} fields={{ questionId: q.id, op: "archive" }} variant="outline" className="h-9 px-3">Archive</ActionButton>}
            </div>
            {q.source_reference && <p className="mt-4 text-caption text-ink-3">Source: {q.source_reference}</p>}
          </Panel>
          <Panel title={`Used in ${usedIn.length} ${usedIn.length === 1 ? "quiz" : "quizzes"}`}>
            {usedIn.length === 0 ? <p className="text-body-sm text-ink-3">Not attached to a quiz yet. Add it from a quiz&apos;s page.</p> : (
              <ul className="space-y-2">{usedIn.map((z) => <li key={z.id} className="flex items-center justify-between gap-2 text-body-sm"><Link href={`/admin/quizzes/${z.id}`} className="truncate hover:underline">{z.title}</Link><StatusBadge status={z.status} /></li>)}</ul>
            )}
          </Panel>
          <Panel title="Danger zone">
            <ActionButton action={deleteQuestion} fields={{ questionId: q.id, redirectTo: "/admin/questions" }} variant="danger" className="h-9 px-3" confirm={{ title: "Delete this question?", body: `It's removed permanently${usedIn.length ? ` from ${usedIn.length} ${usedIn.length === 1 ? "quiz" : "quizzes"}` : ""}, along with its answer options. Archiving keeps it out of quizzes without deleting it.`, label: "Delete question" }}><Trash2 aria-hidden className="h-3.5 w-3.5" />Delete question</ActionButton>
          </Panel>
        </div>
      </div>
    </>
  );
}

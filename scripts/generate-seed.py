#!/usr/bin/env python3
"""Generate supabase/seed.sql from src/content/blender-foundations.json (single source of truth)."""
import json, re, uuid, pathlib

root = pathlib.Path(__file__).resolve().parent.parent
data = json.loads((root / "src/content/blender-foundations.json").read_text())
NS = uuid.UUID("6f0c1d2e-5a4b-4c3d-9e8f-0a1b2c3d4e5f")
uid = lambda *p: str(uuid.uuid5(NS, "/".join(map(str, p))))
q = lambda s: "'" + s.replace("'", "''") + "'"

def arr(items):
    return "array[" + ", ".join(q(i) for i in items) + "]::text[]"

def slugify(t):
    t = t.lower().replace("—", "-")
    t = re.sub(r"[^a-z0-9]+", "-", t).strip("-")
    return t

course_id = uid("course", data["slug"])
out = [
    "-- GENERATED by scripts/generate-seed.py. Re-run after editing blender-foundations.json.",
    "-- Safe to run more than once.",
    "-- The course is seeded as DRAFT. Publish it from Admin > Courses when you are ready.",
    f"insert into public.courses (id, slug, title, subtitle, description, level, category, instructor, learning_outcomes, target_audience, requirements, status) values ({q(course_id)}, {q(data['slug'])}, {q(data['title'])}, {q(data['shortDescription'])}, {q(data['promise'])}, {q(data['level'])}, '3D', 'Samson Odejinmi', {arr(data['learn'])}, {arr(data['forWho'])}, {arr(['A computer that can run Blender (Blender itself is free).'])}, 'draft')",
    "  on conflict (id) do update set",
    "    description = coalesce(public.courses.description, excluded.description),",
    "    category = coalesce(public.courses.category, excluded.category),",
    "    instructor = coalesce(public.courses.instructor, excluded.instructor),",
    "    learning_outcomes = case when coalesce(array_length(public.courses.learning_outcomes, 1), 0) = 0 then excluded.learning_outcomes else public.courses.learning_outcomes end,",
    "    target_audience = case when coalesce(array_length(public.courses.target_audience, 1), 0) = 0 then excluded.target_audience else public.courses.target_audience end,",
    "    requirements = case when coalesce(array_length(public.courses.requirements, 1), 0) = 0 then excluded.requirements else public.courses.requirements end;",
    "-- (Existing status is never changed by this seed.)",
    "",
    "-- Pricing (minor units). Edit rows here or in the table; the site reads them live.",
    "insert into public.course_pricing (course_id, currency, amount_minor, active) values",
    f"  ({q(course_id)}, 'NGN', 2500000, true),",
    f"  ({q(course_id)}, 'USD', 3000, true)",
    "  on conflict (course_id, currency) do update set amount_minor = excluded.amount_minor, active = excluded.active;",
    "",
]
mods, lessons = [], []
for m in data["modules"]:
    mid = uid("module", data["slug"], m["number"])
    mods.append(f"  ({q(mid)}, {q(course_id)}, {m['number']}, {q(m['title'])})")
    for i, l in enumerate(m["lessons"], 1):
        lid = uid("lesson", data["slug"], l["number"])
        slug = slugify(l["title"])
        lessons.append(f"  ({q(lid)}, {q(mid)}, {q(course_id)}, {q(slug)}, {i}, {q(l['number'] + ' ' + l['title'])}, 'published')")

out += ["insert into public.modules (id, course_id, position, title) values", ",\n".join(mods),
        "  on conflict (id) do update set title = excluded.title, position = excluded.position;", "",
        "-- Lessons are seeded as published shells: no video or text yet. Fill video_provider/video_id/content_md in the table.",
        "insert into public.lessons (id, module_id, course_id, slug, position, title, status) values", ",\n".join(lessons),
        "  on conflict (id) do update set title = excluded.title, slug = excluded.slug, position = excluded.position;", ""]
(root / "supabase/seed.sql").write_text("\n".join(out))
print("wrote supabase/seed.sql:", len(mods), "modules,", len(lessons), "lessons")
